#!/usr/bin/env node
/**
 * Generates gateway/internal/wire/planes_gen.go from src/shared/federation/planes.json,
 * so the Go gateway and the TypeScript clients share one list of planes and bounds.
 *
 *   node scripts/gen-gateway-planes.mjs          # write the Go file
 *   node scripts/gen-gateway-planes.mjs --check  # exit 1 when it is out of date
 */

import { readFileSync, writeFileSync } from 'fs'
import { dirname, join } from 'path'
import { fileURLToPath } from 'url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
export const PLANES_JSON = join(root, 'src/shared/federation/planes.json')
export const PLANES_GO = join(root, 'gateway/internal/wire/planes_gen.go')

const goName = (name) => `Plane${name[0].toUpperCase()}${name.slice(1)}`

export function renderPlanesGo(planes) {
  const lines = [
    '// Code generated by scripts/gen-gateway-planes.mjs from src/shared/federation/planes.json. DO NOT EDIT.',
    '',
    'package wire',
    '',
    '// Plane is one outbound priority plane; lower values drain first.',
    'type Plane int',
    '',
    'const (',
    ...planes.map((p, i) => (i === 0 ? `\t${goName(p.name)} Plane = iota` : `\t${goName(p.name)}`)),
    '\tPlaneCount',
    ')',
    '',
    '// PlaneNames are the wire names of the planes (the envelope `plane` hint).',
    `var PlaneNames = [PlaneCount]string{${planes.map((p) => JSON.stringify(p.name)).join(', ')}}`,
    '',
    '// PlaneCapacityFrames bounds each plane queue by frame count.',
    `var PlaneCapacityFrames = [PlaneCount]int{${planes.map((p) => p.capFrames).join(', ')}}`,
    '',
    '// PlaneCapacityBytes bounds each plane queue by size (0 = no size bound).',
    `var PlaneCapacityBytes = [PlaneCount]int{${planes.map((p) => p.capBytes).join(', ')}}`,
    '',
    'func (p Plane) String() string {',
    '\tif p >= 0 && p < PlaneCount {',
    '\t\treturn PlaneNames[p]',
    '\t}',
    '\treturn "unknown"',
    '}',
    '',
    '// PlaneByName resolves a wire plane name.',
    'func PlaneByName(name string) (Plane, bool) {',
    '\tfor i, n := range PlaneNames {',
    '\t\tif n == name {',
    '\t\t\treturn Plane(i), true',
    '\t\t}',
    '\t}',
    '\treturn PlaneControl, false',
    '}',
    '',
  ]
  return lines.join('\n')
}

function main() {
  const planes = JSON.parse(readFileSync(PLANES_JSON, 'utf8'))
  const rendered = renderPlanesGo(planes)
  if (process.argv.includes('--check')) {
    const current = readFileSync(PLANES_GO, 'utf8')
    if (current !== rendered) {
      console.error(`${PLANES_GO} is out of date; run node scripts/gen-gateway-planes.mjs`)
      process.exit(1)
    }
    return
  }
  writeFileSync(PLANES_GO, rendered)
  console.log(`wrote ${PLANES_GO}`)
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main()
