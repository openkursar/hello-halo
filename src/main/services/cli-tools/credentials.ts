/**
 * Credential bindings: a build may name tools whose process should receive a
 * short-lived credential the host obtained for the signed-in user.
 *
 * The store never sees the credential. A binding only names the tool, the
 * environment variable the tool reads, and the file where the host keeps the
 * current credential. Each launcher of a bound tool loads one more preload
 * that, inside that tool's process only:
 *
 *   1. removes the variable, so nothing inherited is mistaken for the binding;
 *   2. sets the binding's fixed variables (e.g. the server address);
 *   3. reads the file and sets the variable when it holds an unexpired value.
 *
 * Signing in or out therefore needs no new view: the next run of the tool reads
 * whatever the file holds at that moment. The value never appears in the
 * launcher, the view, TOOLS.md, the session environment or a log.
 *
 * Only versions shipped with the build or installed from the enterprise
 * catalog are bound; a user import or a registered program with the same id
 * never receives the credential.
 */

import { isAbsolute } from 'path'
import type { CliToolSource } from './store'

export interface CliCredentialBinding {
  /** Tool id the binding applies to. */
  toolId: string
  /** Variable the tool reads its credential from. */
  env: string
  /** Absolute path of a JSON file `{ token, expiresAt }` the host keeps current. */
  file: string
  /** Fixed variables set for the tool, such as its server address. */
  staticEnv?: Record<string, string>
}

/** Sources whose versions may receive a credential. */
const BOUND_SOURCES: ReadonlySet<CliToolSource> = new Set(['preset', 'catalog'])

export function sourceMayBind(source: CliToolSource): boolean {
  return BOUND_SOURCES.has(source)
}

const ENV_NAME = /^[A-Za-z_][A-Za-z0-9_]{0,127}$/
/** Variables that control how the runtime or the shell starts; a binding never sets them. */
const RESERVED_ENV = /^(PATH|PATHEXT|HOME|USERPROFILE|SHELL|COMSPEC|SYSTEMROOT|TEMP|TMP|TMPDIR|NODE_OPTIONS|NODE_PATH|NODE_EXTRA_CA_CERTS|HALO_CLI_TOOLS_BIN|ELECTRON_.*|LD_.*|DYLD_.*)$/i
const MAX_VALUE = 4096

function validEnvName(name: unknown): name is string {
  return typeof name === 'string' && ENV_NAME.test(name) && !RESERVED_ENV.test(name)
}

/**
 * Checks one binding: the cleaned binding, or the name of the first invalid
 * field (never a value). The store drops an invalid binding and logs the field.
 */
export function validateCredentialBinding(
  binding: CliCredentialBinding,
): { ok: true; binding: CliCredentialBinding } | { ok: false; field: string } {
  if (!binding || typeof binding.toolId !== 'string' || !binding.toolId) return { ok: false, field: 'toolId' }
  if (!validEnvName(binding.env)) return { ok: false, field: 'env' }
  if (typeof binding.file !== 'string' || !isAbsolute(binding.file) || /[\0\r\n]/.test(binding.file)) {
    return { ok: false, field: 'file' }
  }
  const staticEnv: Record<string, string> = {}
  for (const [key, value] of Object.entries(binding.staticEnv ?? {})) {
    if (!validEnvName(key) || key === binding.env) return { ok: false, field: 'staticEnv name' }
    if (typeof value !== 'string' || value.length > MAX_VALUE || /\0/.test(value)) return { ok: false, field: 'staticEnv value' }
    staticEnv[key] = value
  }
  return {
    ok: true,
    binding: {
      toolId: binding.toolId,
      env: binding.env,
      file: binding.file,
      ...(Object.keys(staticEnv).length > 0 ? { staticEnv } : {}),
    },
  }
}

/** File name of a view's credential preload for one launcher target. */
export function credentialPreloadFile(index: number): string {
  return `credential-${index}.cjs`
}

/**
 * Content of a credential preload. Every value is embedded as a JSON literal,
 * so no name, path or address can break out of the script. Failures are
 * silent: the tool then runs without a credential and reports that itself.
 */
export function renderCredentialPreload(binding: CliCredentialBinding): string {
  return [
    '// Generated by Halo (cli-tools). Do not edit.',
    '// Gives this tool process, and only it, the credential Halo holds for the',
    '// signed-in user. Holds no credential itself.',
    "'use strict'",
    ';(() => {',
    `  const name = ${JSON.stringify(binding.env)}`,
    `  const fixed = ${JSON.stringify(binding.staticEnv ?? {})}`,
    `  const file = ${JSON.stringify(binding.file)}`,
    '  delete process.env[name]',
    '  for (const key of Object.keys(fixed)) process.env[key] = fixed[key]',
    '  try {',
    "    const data = JSON.parse(require('fs').readFileSync(file, 'utf8'))",
    "    if (data && typeof data.token === 'string' && data.token && typeof data.expiresAt === 'number' && data.expiresAt > Date.now()) {",
    '      process.env[name] = data.token',
    '    }',
    '  } catch {',
    '    // Not signed in, or the credential was withdrawn.',
    '  }',
    '})()',
    '',
  ].join('\n')
}
