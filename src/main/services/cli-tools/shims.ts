/**
 * Thin launchers: one per exposed command, nothing but "run this entry on the
 * bundled runtime with these arguments".
 *
 * A launcher sets ELECTRON_RUN_AS_NODE (and ELECTRON_NO_ATTACH_CONSOLE, which
 * keeps Windows from attaching a console window), then runs the fixed runtime
 * on the fixed entry file, passing arguments through. The POSIX form `exec`s,
 * so cwd, stdio, exit status and signals belong to the tool itself. No login,
 * retry, update check or business decision happens here.
 *
 * On Windows both `<name>.cmd` (cmd.exe / PowerShell) and an extensionless sh
 * twin (Git Bash, which does not resolve `name` to `name.cmd`) are written,
 * the same arrangement as the office runtime's `halo-node`.
 *
 * Known pass-through limits: the tool's own child processes inherit
 * ELECTRON_RUN_AS_NODE, which is what keeps `process.execPath` usable as Node
 * for them; and cmd.exe may ask "Terminate batch job (Y/N)?" on Ctrl+C.
 */

import { CliToolError } from './errors'

/** POSIX single-quote a value: the only character needing care is `'` itself. */
export function shQuote(value: string): string {
  return `'${value.replace(/'/g, `'\\''`)}'`
}

/**
 * cmd.exe cannot escape `"` inside a quoted argument, and `%` expands even
 * inside quotes in a batch file; newlines would end the command.
 */
function cmdPath(value: string): string {
  if (/["\r\n]/.test(value)) {
    throw new CliToolError('PATH_UNSAFE', 'a launcher path contains a character cmd.exe cannot quote')
  }
  return value.replace(/%/g, '%%')
}

export function renderShLauncher(runtimePath: string, entryPath: string): string {
  if (/[\r\n]/.test(runtimePath) || /[\r\n]/.test(entryPath)) {
    throw new CliToolError('PATH_UNSAFE', 'a launcher path contains a line break')
  }
  return [
    '#!/bin/sh',
    '# Generated by Halo (cli-tools). Do not edit.',
    'export ELECTRON_RUN_AS_NODE=1',
    'export ELECTRON_NO_ATTACH_CONSOLE=1',
    `exec ${shQuote(runtimePath)} ${shQuote(entryPath)} "$@"`,
    '',
  ].join('\n')
}

export function renderCmdLauncher(runtimePath: string, entryPath: string): string {
  return [
    '@echo off',
    'rem Generated by Halo (cli-tools). Do not edit.',
    'setlocal',
    'set ELECTRON_RUN_AS_NODE=1',
    'set ELECTRON_NO_ATTACH_CONSOLE=1',
    `"${cmdPath(runtimePath)}" "${cmdPath(entryPath)}" %*`,
    'exit /b %ERRORLEVEL%',
    '',
  ].join('\r\n')
}

/** Files to write for one command on the given platform: name → content. */
export function launcherFiles(
  platform: NodeJS.Platform,
  command: string,
  runtimePath: string,
  entryPath: string
): Array<{ name: string; content: string; executable: boolean }> {
  const sh = { name: command, content: renderShLauncher(runtimePath, entryPath), executable: true }
  if (platform !== 'win32') return [sh]
  return [{ name: `${command}.cmd`, content: renderCmdLauncher(runtimePath, entryPath), executable: false }, sh]
}
