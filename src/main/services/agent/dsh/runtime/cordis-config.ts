interface ToolPlugin {
  /** The row to mount for this caller, or null to leave the block out. */
  render(permits: (tool: string) => boolean): string | null
}

/**
 * A block dsh registers as one group. Mounted only when the caller may use
 * every Halo tool it stands in for: the plugin offers no way to split the
 * group, and withholding one Halo cannot fully permit is the only direction
 * that cannot over-grant.
 */
function bundle(grants: readonly string[], yaml: string): ToolPlugin {
  return { render: (permits) => (grants.every(permits) ? yaml : null) }
}

