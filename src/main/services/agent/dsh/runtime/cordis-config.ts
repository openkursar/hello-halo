export interface CordisComposition {
  /**
   * Halo tool names the session may not use. Undefined means unrestricted —
   * the shape Halo's own callers pass; a guest session arrives with the
   * inverted whitelist its policy produced.
   */
  disallowedTools?: readonly string[]
  /** MCP servers to connect, keyed by Halo's server id. */
  mcpServers?: Record<string, ExternalMcpServer>
  /** Working directory for an MCP server that declares none. */
  workDir?: string
}

export interface MaterializedCordisConfig {
  /** Absolute path of the written composition. */
  path: string
  /**
   * Environment the composition reads at load. Merged into the child env by
   * the launch spec; the values are secrets and ephemeral ports, which is why
   * they are not in the file.
   */
  env: Record<string, string>
  /** MCP server names the composition connects, in row order. */
  mcpServers: string[]
}

/**
 * Write the composition into `dir` and describe what the child needs to load it.
 *
 * Generated rather than shipped as a static asset: a static file would have to
 * survive `electron-vite`'s main-process bundle and be re-declared in the
 * packaging file list, and nothing would keep it in sync with this module.
 * Plugin names resolve out of the runtime's own builtins rather than relative
 * to this file, so Halo's data directory is a valid home for it.
 *
 * The filename carries a digest of the content because the loader watches the
 * path it booted from and hot-reloads it. Sessions with different tool sets
 * share one data directory, so a fixed name would let a later launch rewrite
 * the document a running child is still watching — handing it another
 * session's permissions. That argument is why no per-session value may be
 * interpolated into the text: two sessions differing only in an MCP token or a
 * bridge port must keep sharing one file, and the differing values ride in the
 * returned environment instead.
 */
export function materializeCordisConfig(
  dir: string,
  composition: CordisComposition = {}
): MaterializedCordisConfig {
  const denied = new Set(composition.disallowedTools ?? [])
  const mounted = TOOL_PLUGINS.map((plugin) => plugin.render((tool) => !denied.has(tool))).filter(
    (yaml): yaml is string => yaml !== null
  )
  const mcp = buildDshMcpComposition(
    composition.mcpServers ?? {},
    composition.workDir ?? process.cwd()
  )
  for (const { name, reason } of mcp.skipped) {
    console.warn(`[Dsh][runtime] MCP server '${name}' not mounted: ${reason}`)
  }

  const text = [BASE_PLUGINS, mounted.join('\n'), mcp.yaml].filter(Boolean).join('\n')
  const digest = createHash('sha256').update(text).digest('hex').slice(0, 12)
  const configPath = path.join(dir, `halo.cordis.${digest}.yml`)
  const env = { [DSH_MCP_SERVERS_ENV]: mcp.env }
  mkdirSync(dir, { recursive: true })

  // Skip the write when unchanged: the loader watches this path for HMR.
  let existing: string | null = null
  try {
    existing = readFileSync(configPath, 'utf-8')
  } catch {
    existing = null
  }
  if (existing === text) return { path: configPath, env, mcpServers: mcp.mounted }

  writeFileSync(configPath, text, 'utf-8')
  console.log(
    `[Dsh][runtime] wrote cordis config path=${configPath} bytes=${text.length} ` +
      `toolPlugins=${mounted.length}/${TOOL_PLUGINS.length} mcpServers=${mcp.mounted.length}`
  )
  return { path: configPath, env, mcpServers: mcp.mounted }
}
