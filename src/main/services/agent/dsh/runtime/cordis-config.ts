/**
 * The cordis plugin composition Halo boots the dsh runtime with.
 *
 * Tracks upstream's `sdk-minimal` bundle (`packages/bundle/sdk-minimal`): an
 * explicit kernel that owns every service row rather than layering over
 * `dsh-base`. It departs from that bundle where Halo, not the harness, is the
 * product:
 *   - no DeepSeek telemetry rows (`session-log-deepseek`,
 *     `plugin-package-inventory-deepseek`, `deepseek-llm-api-extensions`):
 *     they upload session logs and plugin inventories to DeepSeek whichever
 *     vendor the user chose;
 *   - no `dsh-sdk-app` startup provider: the entry generated by
 *     `runtimes/dsh/build.mjs` owns the process lifecycle;
 *   - sandbox, skill, web and subagent rows, which are Halo features the
 *     minimal kernel does not carry.
 *
 * Composition is also the only enforcement point Halo has over what the model
 * may do: the runtime exposes no per-call approval channel and no tool filter
 * outside the child, so a tool a caller must not use has to be a tool the
 * runtime never registers — see `TOOL_PLUGINS`.
 *
 * stdout is reserved for JSON-RPC, so nothing here may write to it: no console
 * logger, no terminal UI, no approval UI.
 *
 * Config values that vary per launch are read from the child env rather than
 * interpolated into the text, so this document is a constant and one runtime's
 * settings can never leak into another's. `!!js` expressions are evaluated by
 * the cordis loader inside the child.
 *
 * Plugins are named `cordis:<id>` rather than by package. That prefix is the
 * loader's escape hatch for plugins the host supplies directly: it reads
 * `loader.builtins[id]` and never resolves a module from disk. The engine ships
 * as one bundled file with every plugin registered there (see
 * `runtimes/dsh/manifest.cjs`), so a package name here would send the
 * loader looking for a `node_modules` tree the packaged app no longer has. Any
 * id used below must exist in that manifest — enforced by
 * `tests/unit/services/agent/dsh/runtime-manifest.test.ts`.
 */

